# a_i = 1 entries (i,j ∈ {3,4,5}): M[i,j] ∈ Z/2Z, M[i,j] mod 2 = δ_{ij}.
#   Forced: 1 choice for entire block.
#
# Off-diagonal (i ∈ {1,2}, j ∈ {3,4,5}): M[i,j] = value in {0,2} ⊂ Z/4Z, mod 2 = 0 (already forced).
#   So M[i,j] ∈ {0, 2}: 2 choices each. 2×3 = 6 entries. 2^6 = 64 choices.
#
# Off-diagonal (i ∈ {3,4,5}, j ∈ {1,2}): M[i,j] ∈ Z/2Z, mod 2 = 0. M[i,j] = 0: 1 choice.
#   3×2 = 6 entries. 1^6 = 1 choice.
#
# |ker| = 16 * 1 * 64 * 1 = 1024.
#
# |Aut(G)| = 64512 * 1024 = 66060288.

# Hmm wait, this doesn't look right. Let me double-check.

# Actually wait. The kernel of the reduction map restricted to Aut(G) is 
# {M ∈ End(G) : M ≡ I mod 2 AND M is an automorphism}.
# But if M ≡ I mod 2, is M automatically an automorphism? 
# Since M mod 2 = I ∈ GL(5, F_2), yes! An endomorphism whose mod-p reduction is 
# invertible IS an automorphism. (Standard result for finitely generated Z/p^kZ-modules.)
# So yes, |ker| counts all endomorphisms congruent to I mod 2.

# |Aut(G)| = |{invertible mod-2 matrices}| * |ker| = 64512 * 1024 = 66060288.

# Let me verify this with a brute-force computation for a slightly smaller group.
# G = Z/4Z × Z/2Z × Z/2Z (type (2,1,1)):
# Endomorphism matrix entries:
# [Z/4Z  Z/2Z' Z/2Z']   where Z/2Z' means Hom(Z/2Z, Z/4Z) = {0,2}
# [Z/2Z  Z/2Z  Z/2Z ]
# [Z/2Z  Z/2Z  Z/2Z ]
# (Z/2Z in the first column of rows 2,3 means Hom(Z/4Z, Z/2Z) ≅ Z/2Z)
#
# Mod-2 reduction:
# [*  0  0]
# [*  *  *]
# [*  *  *]
# Block lower triangular: A is 1×1, D is 2×2.
# |{invertible}| = |GL(1,F_2)| * |M_{2×1}(F_2)| * |GL(2,F_2)| = 1 * 4 * 6 = 24.
# |ker|: top-left: M_{11} ∈ {1,3}: 2. Top-right: M_{12}, M_{13} ∈ {0,2}: 4.
#         Bottom-left: M_{21}, M_{31} ∈ Z/2Z, forced 0: 1. Bottom-right 2×2: forced I: 1.
# |ker| = 2 * 4 * 1 * 1 = 8.
# |Aut(G)| = 24 * 8 = 192.

# Let me verify this by brute force.
from itertools import product as cart_product

def aut_count_brute(group_orders):
    """Count automorphisms of Z/d_1 × ... × Z/d_k by brute force."""
    n = len(group_orders)
    G_size = 1
    for d in group_orders:
        G_size *= d
    
    # Generate all group elements
    ranges = [list(range(d)) for d in group_orders]
    elements = list(cart_product(*ranges))
    
    # An endomorphism is determined by images of generators
    generators = []
    for i in range(n):
        g = [0] * n
        g[i] = 1
        generators.append(tuple(g))
    
    def add(x, y):
        return tuple((x[i] + y[i]) % group_orders[i] for i in range(n))
    
    def scale(c, x):
        return tuple((c * x[i]) % group_orders[i] for i in range(n))
    
    # For each generator e_i of order d_i, φ(e_i) must have order dividing d_i.
    # The image of e_i under φ determines φ on the entire cyclic subgroup.
    # Valid images for e_i: elements x such that d_i * x = 0 in G.
    
    valid_images = []
    for i in range(n):
        d = group_orders[i]
        valid = []
        for x in elements:
            if scale(d, x) == tuple([0]*n):
                valid.append(x)
        valid_images.append(valid)
    
    # Count automorphisms
    count = 0
    for imgs in cart_product(*valid_images):
        # Check if the map is bijective
        # The map sends e_i to imgs[i], extended linearly
        # Check: every element has a unique preimage
        image_set = set()
        valid = True
        for elem in elements:
            # φ(elem) = sum of elem[i] * imgs[i]
            result = tuple([0]*n)
            for i in range(n):
                result = add(result, scale(elem[i], imgs[i]))
            image_set.add(result)
        
        if len(image_set) == G_size:
            count += 1
    
    return count

