#   M[i,j] ∈ Hom(Z/4Z, Z/2Z) ≅ Z/2Z. M[i,j] mod 2 is unrestricted.
# For entries with a_i = 2, a_j = 1 (i ∈ {1,2}, j ∈ {3,4,5}):
#   M[i,j] ∈ Hom(Z/2Z, Z/4Z) ≅ Z/2Z. But the IMAGE is in {0, 2} ⊂ Z/4Z.
#   So M[i,j] mod 2 = 0 ALWAYS.

# So the mod-2 matrix has the form:
# [*  *  0  0  0]
# [*  *  0  0  0]  where * entries are unrestricted in F_2
# [*  *  *  *  *]
# [*  *  *  *  *]
# [*  *  *  *  *]
#
# This is a matrix in M_5(F_2) with the upper-right 2×3 block being all zeros.
# The invertible such matrices form a subgroup of GL(5, F_2).
#
# For invertibility: the matrix has the block form [A  0; C  D] where A is 2×2, C is 3×2, D is 3×3.
# This is invertible iff both A and D are invertible (block lower triangular).
# |{invertible}| = |GL(2, F_2)| * |M_{3×2}(F_2)| * |GL(3, F_2)|
# = 6 * 2^6 * |GL(3, F_2)| ... wait, C is a free 3×2 matrix, unrestricted.
# = 6 * 64 * 168
# |GL(3, F_2)| = (8-1)(8-2)(8-4) = 7*6*4 = 168.
# Total: 6 * 64 * 168 = 64512.
#
# Now the kernel: mod-2 matrix = I.
# a_i = 2 entries (i,j ∈ {1,2}): M[i,j] ∈ Z/4Z, M[i,j] mod 2 = δ_{ij}.
#   M[i,i] ∈ {1,3}: 2 choices each.
#   M[i,j] (i≠j, i,j ∈ {1,2}): M[i,j] ∈ Z/4Z, M[i,j] mod 2 = 0. M[i,j] ∈ {0,2}: 2 choices each.
#   2×2 block: 2^4 = 16 choices.
